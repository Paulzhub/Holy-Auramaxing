create function pg_temp.case_mismatches() returns integer language plpgsql as $$
declare r record; bad integer := 0;
begin
  for r in select * from cases order by n loop
    perform pg_temp.seq('00000000-0000-7000-8000-000000005002', '2025-01-01', r.pattern, '2027-12-01 12:00+00');
    if pg_temp.st('00000000-0000-7000-8000-000000005002') <> r.level || '/' || r.progress || '/' || r.highest then
      bad := bad + 1;
    end if;
  end loop;
  return bad;
end;
$$;
