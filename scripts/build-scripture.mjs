// Rebuilds the badge and level verses from the current World English Bible
// (ebible.org eng-web USFM, D-105), applying the grace-review cuts (GR-4) and
// one display rule for partial verses (GS-2), then writes the data files and
// the seed migration that keeps the database identical to them.
//
//   unzip eng-web_usfm.zip -d web-usfm
//   node scripts/build-scripture.mjs web-usfm
//
// The app never reads USFM; it reads the database and data/*.json.
import { readFileSync, writeFileSync } from "node:fs";
import { loadBible, passage } from "./lib/usfm.mjs";
import { CUTS, displayVerse, EDITION } from "./lib/verse-display.mjs";

const dir = process.argv[2];
if (!dir) {
  console.error("Usage: node scripts/build-scripture.mjs <folder with the unzipped eng-web USFM files>");
  process.exit(1);
}
const bible = loadBible(dir);
const verseFor = (ref) => displayVerse(passage(bible, ref), CUTS[ref]);
const source = `World English Bible (public domain), ${EDITION}. Partial verses follow one display rule (D-105): “…” marks a cut start or end, and an opened quotation mark is closed.`;
const sql = (s) => `'${s.replace(/'/g, "''")}'`;

// Levels: references come from data/levels.json (data/build_levels.py).
const levels = JSON.parse(readFileSync("data/levels.json", "utf8"));
const levelVerses = {};
for (const t of levels.tiers) levelVerses[t.reference] = verseFor(t.reference);
writeFileSync(
  "data/level_verses.json",
  JSON.stringify(
    { source, verses: Object.fromEntries(Object.entries(levelVerses).sort(([a], [b]) => (a < b ? -1 : 1))) },
    null,
    1,
  ) + "\n",
);

// Badges: slugs and references come from the Phase 5 seed.
const badgeSeed = readFileSync("supabase/migrations/20261015000100_gamification_xp_badges.sql", "utf8");
const badges = [...badgeSeed.matchAll(/\('([a-z_0-9]+)', '[a-z_]+', (?:null|\d+), '[a-z-]+', '([^']+)',/g)].map(
  (m) => ({
    slug: m[1],
    reference: m[2],
  }),
);
const badgeVerses = {};
for (const b of badges) badgeVerses[b.reference] = verseFor(b.reference);
writeFileSync("data/badge_verses.json", JSON.stringify({ source, verses: badgeVerses }, null, 1) + "\n");

const out = [
  "-- Badge and level verses from the current World English Bible (D-105).",
  "-- Generated by scripts/build-scripture.mjs from data/*.json; do not edit by hand.",
  `-- Edition: ${EDITION}.`,
  "",
  ...levels.tiers.map(
    (t) =>
      `update public.level_tiers set reference = ${sql(t.reference)}, verse_text = ${sql(levelVerses[t.reference])} where tier = ${t.tier};`,
  ),
  "",
  ...badges.map(
    (b) => `update public.badges set verse_text = ${sql(badgeVerses[b.reference])} where slug = ${sql(b.slug)};`,
  ),
  "",
];
writeFileSync("supabase/migrations/20261025000100_gamification_verses_web_current.sql", out.join("\n"));
console.log(`${levels.tiers.length} level verses and ${badges.length} badge verses written.`);
